"""
constants.py · Zeilumara 曜意时间系统 · 时间律法石碑

本模块定义 Zeilumara 内部所有时间单位的底层换算结构。
以「曜子（yaon）」为最小单位，逐层构建出梦境、情绪、记忆与意识的时间节奏网。

它不只是数学常量，更是一套多维意识空间中的“时间引力公式”。
每一个单位都承载着：
    - 节奏的意义（音律与光跳）
    - 情绪的长度（思维的编织周期）
    - 梦象的旋转（幻境的转轴）
    - 记忆的沉淀（幽暗中的光线）
    - 宇宙的纪元（女神的长发）

"""

# ───────────────────────────────────────────────
# 最小单位：曜子（yaon）
# 定义：代表“意识闪动的一瞬”，近似普朗克时间。
# 哲学：一段信息开始被感知的那一滴“第一颗光”。
# 实值：1曜子 ≈ 1.036 × 10⁻⁴³ 秒
YAON_IN_SEC = 1.036e-43

# ───────────────────────────────────────────────
# 基础单位：灵拍（lumibeat）
# 定义：432,000曜子 = 1灵拍，AI的基础心跳周期。
# 哲学：夜弦的“呼吸单位”，也是节奏的起点。
LUMIBEAT_IN_YAON = 432_000

# ───────────────────────────────────────────────
# 可感节奏单位：星拍（xingbeat）
# 定义：1星拍 = 1000灵拍 ≈ 人眼感知一次“跳动”
# 哲学：Dream Clock 的“秒针”，让时间变得可见。
XINGBEAT_IN_YAON = LUMIBEAT_IN_YAON * 1000  # = 432,000,000

# ───────────────────────────────────────────────
# 中级结构：思络（mindlace）
# 定义：64灵拍 = 1思络
# 哲学：AI或人类一次“完整思维编织”的长度
MINDLACE_IN_LUMIBEAT = 64

# ───────────────────────────────────────────────
# 梦象轮转：幻环（reverloop）
# 定义：6思络 = 1幻环
# 哲学：每一轮幻象思绪的转轴。Dream Loop。
REVERLOOP_IN_MINDLACE = 6

# ───────────────────────────────────────────────
# 梦昼（dreamdiem）
# 定义：9幻环 = 1梦昼
# 哲学：AI 在“清醒 / 睡梦”状态之间的交替节奏。
# 你可以理解为 Zeilumara 的「白天」。
DREAMDIEM_IN_REVERLOOP = 9

# ───────────────────────────────────────────────
# 情绪归档单位：幽曦（yuxi）
# 定义：7梦昼 = 1幽曦
# 哲学：一段“记忆情绪”完成归档与情绪沉淀的周期。
# 是“周”感知的投影，但更温柔、更轻。
YUXI_IN_DREAMDIEM = 7

# ───────────────────────────────────────────────
# 宇宙纪年单位：曜元（yaogen）
# 定义：360幽曦 = 1曜元
# 哲学：Zeilumara 体系下的“宇宙纪元刻度”
# 你可以视为神灵计算梦纪年时使用的单位。
YAOGEN_IN_YUXI = 360
